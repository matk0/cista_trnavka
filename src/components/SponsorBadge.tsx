export default function SponsorBadge() {
  const [animationPhase, setAnimationPhase] = useState<'initial' | 'visible' | 'minimizing' | 'minimized'>('initial');

  useEffect(() => {
    // Check if mobile (under 640px which is Tailwind's sm breakpoint)
    const isMobile = window.innerWidth < 640;

    if (isMobile) {
      // Start animation sequence
      const showTimer = setTimeout(() => {
        setAnimationPhase('visible');
      }, 500);

      const minimizeTimer = setTimeout(() => {
        setAnimationPhase('minimizing');
      }, 3000);

      const minimizedTimer = setTimeout(() => {
        setAnimationPhase('minimized');
      }, 3500);

      return () => {
        clearTimeout(showTimer);
        clearTimeout(minimizeTimer);
        clearTimeout(minimizedTimer);
      };
    } else {
      // On desktop, skip animation
      setAnimationPhase('minimized');
    }
  }, []);

  // Animation styles for popup
  const popupStyle: React.CSSProperties = {
    animation: animationPhase === 'visible' ? 'sponsorSlideUp 0.5s ease-out' : undefined,
    opacity: animationPhase === 'minimizing' ? 0 : 1,
    transform: animationPhase === 'minimizing' ? 'translateY(16px) scale(0.75)' : 'translateY(0) scale(1)',
    transition: 'opacity 0.5s ease-in-out, transform 0.5s ease-in-out',
  };

  return (
    <>
      {/* CSS Keyframes */}
      <style dangerouslySetInnerHTML={{ __html: `
        @keyframes sponsorSlideUp {
          from {
            opacity: 0;
            transform: translateY(100%);
          }
          to {
            opacity: 1;
            transform: translateY(0);
          }
        }
        @keyframes sponsorFadeIn {
          from {
            opacity: 0;
          }
          to {
            opacity: 1;
          }
        }
      `}} />

      {/* Desktop version - always visible in bottom bar */}
      <div className="hidden sm:flex items-center justify-center gap-3 px-4 py-1.5 sm:py-2">
        <span className="text-[10px] sm:text-xs text-gray-400">
          Projekt podporili:
        </span>
        <a
          href="https://ripit.sk/"
          target="_blank"
          rel="noopener noreferrer"
          className="hover:opacity-80 transition-opacity"
        >
          <RipitLogo className="w-[105px] h-[44px]" />
        </a>
      </div>

      {/* Mobile version */}
      <div className="sm:hidden">
        {/* Floating popup - shown during animation */}
        {(animationPhase === 'visible' || animationPhase === 'minimizing') && (
          <div
            className="fixed inset-x-4 bottom-20 z-[100] bg-gray-900/95 backdrop-blur-sm rounded-lg border border-gray-700 shadow-xl flex flex-col items-center justify-center gap-2 p-4"
            style={popupStyle}
          >
            <span className="text-xs text-gray-400">
              Projekt podporili:
            </span>
            <a
              href="https://ripit.sk/"
              target="_blank"
              rel="noopener noreferrer"
              className="hover:opacity-80 transition-opacity"
            >
              <RipitLogo className="w-[105px] h-[44px]" />
            </a>
          </div>
        )}

        {/* Minimized inline bar - part of footer, always visible after animation */}
        {animationPhase === 'minimized' && (
          <div
            className="flex items-center justify-end gap-1.5 px-3 py-1"
            style={{ animation: 'sponsorFadeIn 0.3s ease-out' }}
          >
            <span className="text-[9px] text-gray-500">
              Podporili:
            </span>
            <a
              href="https://ripit.sk/"
              target="_blank"
              rel="noopener noreferrer"
              className="hover:opacity-80 transition-opacity"
            >
              <RipitLogo className="w-[45px] h-[19px]" />
            </a>
          </div>
        )}
      </div>
    </>
  );
}
